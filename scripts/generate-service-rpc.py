#!/usr/bin/env python3
"""Generate explicit domain RPC contracts and clients from the API method inventory."""

import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
HEADER = "// Code generated by scripts/generate-service-rpc.py. DO NOT EDIT.\n"


def contract(service):
    lines = [
        HEADER,
        'syntax = "proto3";\n',
        "package mall.v1;\n",
        'option go_package = "github.com/davveo/lumo/api/mall/v1;mallv1";\n',
        'import "api/mall/v1/service_request.proto";\n',
        f"service {service['name']}Service {{",
    ]
    for method in service["methods"]:
        lines.append(f"  rpc {method['method']}(ServiceRequest) returns (ServiceResponse);")
    lines.append("}\n")
    return "\n".join(lines)


def go_source(services):
    lines = [
        HEADER,
        "package platform\n",
        'import ("context"; "github.com/davveo/lumo/internal/constants";',
        'mallv1 "github.com/davveo/lumo/api/mall/v1"; "google.golang.org/grpc")\n',
        "// Clients exposes named operations without an action parameter.",
        "type Clients struct {",
    ]
    for service in services:
        lines.append(f"{service['name']} {service['name']}Methods")
    lines.extend(["}", "func NewClients(caller Caller) Clients { return Clients{"])
    for service in services:
        lines.append(f"{service['name']}: {service['name']}Methods{{caller: caller}},")
    lines.extend(["}}", "var namedOperationActions = map[string]map[string]string{"])
    for service in services:
        lines.append(f"constants.{service['constant']}: {{")
        for method in service["methods"]:
            lines.append(f'"{method["method"]}": constants.{method["action"]},')
        lines.append("},")
    lines.append("}")
    for service in services:
        name = service["name"]
        lines.append(f"type {name}Methods struct {{ caller Caller }}")
        for method in service["methods"]:
            operation, action = method["method"], method["action"]
            lines.extend(
                [
                    f"func (client {name}Methods) {operation}(",
                    "ctx context.Context, request Request,",
                    ") (Result, error) {",
                    "return invokeMethod(",
                    f'ctx, client.caller, constants.{service["constant"]}, "{operation}",',
                    f"constants.{action}, request,",
                    ")}",
                ]
            )
    lines.extend(
        [
            "type serviceRPC struct {",
            "fullMethod string",
            "invoke func(context.Context, grpc.ClientConnInterface, *mallv1.ServiceRequest) "
            "(*mallv1.ServiceResponse, error)",
            "}",
            "var namedServiceRPCs = map[string]map[string]serviceRPC{",
        ]
    )
    domains = [service for service in services if not service["existing_contract"]]
    for service in domains:
        lines.append(f"constants.{service['constant']}: {{")
        for method in service["methods"]:
            name, operation = service["name"], method["method"]
            lines.extend(
                [
                    f"constants.{method['action']}: {{",
                    f"fullMethod: mallv1.{name}Service_{operation}_FullMethodName,",
                    "invoke: func(ctx context.Context, connection grpc.ClientConnInterface,",
                    "request *mallv1.ServiceRequest) (*mallv1.ServiceResponse, error) {",
                    f"return mallv1.New{name}ServiceClient(connection).{operation}(ctx, request)",
                    "},},",
                ]
            )
        lines.append("},")
    lines.append("}")
    for service in domains:
        name = service["name"]
        lines.append(
            f"type {service['service']}RPCServer struct {{ mallv1.Unimplemented{name}ServiceServer; "
            "operations map[string]Operation }"
        )
        for method in service["methods"]:
            lines.extend(
                [
                    f"func (server *{service['service']}RPCServer) {method['method']}(",
                    "ctx context.Context, request *mallv1.ServiceRequest,",
                    ") (*mallv1.ServiceResponse, error) {",
                    f"return serveMethod(ctx, server.operations[constants.{method['action']}], request)",
                    "}",
                ]
            )
    lines.extend(
        [
            "func registerServiceMethods(registrar grpc.ServiceRegistrar, module Module) {",
            "switch module.Name {",
        ]
    )
    for service in domains:
        lines.extend(
            [
                f"case constants.{service['constant']}:",
                f"mallv1.Register{service['name']}ServiceServer(",
                f"registrar, &{service['service']}RPCServer{{operations: module.Operations}},",
                ")",
            ]
        )
    lines.extend(["}}", ""])
    result = subprocess.run(
        ["gofmt"], input="\n".join(lines), capture_output=True, text=True, check=True
    )
    return result.stdout


def validate(services):
    constants = (ROOT / "internal/constants/actions.go").read_text()
    actions = set(re.findall(r'\b(Action\w+)\s*=\s*"[^"\n]*"', constants))
    seen_services = set()
    for service in services:
        name = service["service"]
        if name in seen_services:
            raise ValueError(f"Duplicate service: {name}")
        seen_services.add(name)
        seen_actions, seen_methods = set(), set()
        for method in service["methods"]:
            action, operation = method["action"], method["method"]
            if action not in actions or action in seen_actions or operation in seen_methods:
                raise ValueError(f"Invalid or duplicate operation in {name}: {method}")
            if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", operation):
                raise ValueError(f"Invalid RPC method: {operation}")
            seen_actions.add(action)
            seen_methods.add(operation)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without writing")
    options = parser.parse_args()
    services = json.loads((ROOT / "api/mall/v1/service_methods.json").read_text())["services"]
    validate(services)
    outputs = {ROOT / "internal/platform/service_methods_generated.go": go_source(services)}
    for service in services:
        if not service["existing_contract"]:
            outputs[ROOT / f"api/mall/v1/{service['service']}.proto"] = contract(service)
    stale = []
    for path, content in outputs.items():
        if options.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise SystemExit("Generated RPC files are stale; run `make proto`:\n" + "\n".join(stale))
    print(f"{'Checked' if options.check else 'Generated'} {len(services)} services and "
          f"{sum(len(service['methods']) for service in services)} named methods.")


if __name__ == "__main__":
    main()
