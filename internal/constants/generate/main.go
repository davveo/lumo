// Command generate exports the shared Go string enums to the browser without
// requiring a Go runtime, a bundler, or a second hand-maintained value list.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

func main() {
	source := flag.String("source", ".", "directory containing enum declarations")
	output := flag.String("output", "../../web/dist/constants.js", "generated browser script")
	check := flag.Bool("check", false, "fail when the browser script is out of date")
	flag.Parse()
	if err := run(*source, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(source, output string, check bool) error {
	files, err := filepath.Glob(filepath.Join(source, "*.go"))
	if err != nil {
		return err
	}
	groups := map[string]map[string]string{}
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		for _, declaration := range file.Decls {
			decl, ok := declaration.(*ast.GenDecl)
			if !ok || decl.Tok != token.CONST || decl.Doc == nil {
				continue
			}
			group := ""
			for _, comment := range decl.Doc.List {
				text := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
				if strings.HasPrefix(text, "enum:") {
					group = strings.TrimSpace(strings.TrimPrefix(text, "enum:"))
				}
			}
			if group == "" {
				continue
			}
			if !token.IsIdentifier(group) || !ast.IsExported(group) || groups[group] != nil {
				return fmt.Errorf("%s: invalid or repeated enum group %q", path, group)
			}
			values := map[string]string{}
			for _, specification := range decl.Specs {
				spec := specification.(*ast.ValueSpec)
				if spec.Type != nil || len(spec.Names) != len(spec.Values) {
					return fmt.Errorf("%s: %s must contain explicit untyped string constants", path, group)
				}
				for index, name := range spec.Names {
					key := strings.TrimPrefix(name.Name, group)
					literal, ok := spec.Values[index].(*ast.BasicLit)
					if !ok || literal.Kind != token.STRING || key == name.Name || !ast.IsExported(key) {
						return fmt.Errorf("%s: %s must use the %s prefix and a string literal", path, name.Name, group)
					}
					value, err := strconv.Unquote(literal.Value)
					if err != nil {
						return fmt.Errorf("%s: invalid value for %s", path, name.Name)
					}
					values[key] = value
				}
			}
			groups[group] = values
		}
	}
	if len(groups) == 0 {
		return fmt.Errorf("no string enum groups found in %s", source)
	}
	data, err := json.MarshalIndent(groups, "  ", "  ")
	if err != nil {
		return err
	}
	var script bytes.Buffer
	script.WriteString("// Code generated by go generate ./internal/constants; DO NOT EDIT.\n")
	script.WriteString("(function () {\n  'use strict';\n  if (Object.hasOwn(window, 'LumoConstants')) return;\n  const values = ")
	script.Write(data)
	script.WriteString(";\n  for (const group of Object.values(values)) Object.freeze(group);\n  Object.defineProperty(window, 'LumoConstants', {value: Object.freeze(values), writable: false, configurable: false});\n})();\n")
	if check {
		existing, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(existing, script.Bytes()) {
			return fmt.Errorf("%s is out of date; run go generate ./internal/constants", output)
		}
		return nil
	}
	return os.WriteFile(output, script.Bytes(), 0644)
}
